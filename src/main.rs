#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
struct HtmlCapture {
    png: Vec<u8>,
    width: u32,
    height: u32,
    css_width: u32,
    css_height: u32,
    /// Layout width reported by a print-mode renderer before printing, used
    /// to scale fixed-width pages down to the printable area. 0 for captures.
    scroll_width: u32,
}

struct HtmlPreviewState {
    docs: Mutex<Vec<(String, String)>>,
    pending: Mutex<HashMap<String, std::sync::mpsc::Sender<Result<HtmlCapture, String>>>>,
}

impl HtmlPreviewState {
    fn new() -> Self {
        Self {
            docs: Mutex::new(Vec::new()),
            pending: Mutex::new(HashMap::new()),
        }
    }

    fn get(&self, token: &str) -> Option<String> {
        self.docs
            .lock()
            .unwrap()
            .iter()
            .find(|(t, _)| t == token)
            .map(|(_, html)| html.clone())
    }

    fn prepare(&self, token: &str) -> std::sync::mpsc::Receiver<Result<HtmlCapture, String>> {
        let (tx, rx) = std::sync::mpsc::channel();
        self.pending.lock().unwrap().insert(token.to_string(), tx);
        rx
    }

    fn finish(&self, token: &str, result: Result<HtmlCapture, String>) {
        if let Some(tx) = self.pending.lock().unwrap().remove(token) {
            let _ = tx.send(result);
        }
    }

    fn cancel(&self, token: &str) {
        self.pending.lock().unwrap().remove(token);
    }

    fn remove_doc(&self, token: &str) {
        self.docs.lock().unwrap().retain(|(t, _)| t != token);
    }

    /// Keep at most 8 registered documents, but never evict a document whose
    /// renderer window is still waiting for it (the hidden renderer and
    /// sandbox preview share this ring).
    fn push_doc(&self, token: String, html: String) {
        let mut docs = self.docs.lock().unwrap();
        docs.push((token, html));
        if docs.len() > 8 {
            let pending = self.pending.lock().unwrap();
            while docs.len() > 8 {
                let Some(index) = docs
                    .iter()
                    .position(|(candidate, _)| !pending.contains_key(candidate))
                else {
                    break;
                };
                docs.remove(index);
            }
        }
    }
}

fn random_token(prefix: &str) -> String {
    let mut bytes = [0u8; 16];
    if getrandom::fill(&mut bytes).is_err() {
        // Extremely unlikely; fall back to a time/counter seed rather than
        // failing preview/export.
        let seed = std::time::SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0)
            ^ u128::from(TEMP_COUNTER.fetch_add(1, Ordering::Relaxed));
        bytes.copy_from_slice(&seed.to_le_bytes());
    }
    format!(
        "{prefix}{}",
        bytes.iter().map(|b| format!("{b:02x}")).collect::<String>()
    )
}

