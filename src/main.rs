fn main() {
    use tauri::Manager;
    tauri::Builder::default()
        .manage(VaultState::new())
        .manage(HtmlPreviewState::new())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        // Serve vault images to the webview (local image references). The
        // async variant runs the (cached) file read off the main thread.
        .register_asynchronous_uri_scheme_protocol("rmd", |ctx, request, responder| {
            let state = ctx.app_handle().state::<VaultState>();
            let root = state.root.lock().unwrap().clone();
            let cache = state.cache.clone();
            tauri::async_runtime::spawn(async move {
                responder.respond(serve_rmd(root, &cache, &request));
            });
        })
        // Built-in renderer: serve the generated document to a hidden
        // Tauri webview when no external Chromium is installed.
        .register_uri_scheme_protocol("rmdhtml", |ctx, request| {
            let state = ctx.app_handle().state::<HtmlPreviewState>();
            serve_html_preview(&state, &request)
        })
        .invoke_handler(tauri::generate_handler![
            list_notes,
            list_folders,
            read_note,
            save_note,
            create_note,
            rename_note,
            delete_note,
            move_note,
            search_notes,
            save_export,
            fetch_image_bytes,
            set_notes_root,
            read_local_image,
            render_html_note,
            html_preview_finish,
            set_html_preview,
            selftest_config,
            selftest_write,
            selftest_finish
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

