// ---------------- Remote image fetching ----------------

const IMAGE_LIMIT: u64 = 25 * 1024 * 1024; // 25 MB

/// True for addresses that are not safe to fetch from an untrusted note:
/// loopback, private/link-local/CGNAT, documentation, multicast and reserved
/// ranges. Redirects are checked with the same function.
fn is_public_ip(ip: IpAddr) -> bool {
    match ip {
        IpAddr::V4(v4) => is_public_ipv4(v4),
        IpAddr::V6(v6) => is_public_ipv6(v6),
    }
}

fn is_public_ipv4(ip: Ipv4Addr) -> bool {
    let o = ip.octets();
    !(ip.is_private()
        || ip.is_loopback()
        || ip.is_link_local()
        || ip.is_broadcast()
        || ip.is_documentation()
        || ip.is_unspecified()
        || ip.is_multicast()
        || o[0] == 0
        || (o[0] == 100 && (64..=127).contains(&o[1]))
        // 192.0.0.0/24 IETF protocol assignments
        || (o[0] == 192 && o[1] == 0 && o[2] == 0)
        || (o[0] == 192 && o[1] == 88 && o[2] == 99)
        || (o[0] == 198 && (o[1] == 18 || o[1] == 19))
        || o[0] >= 240)
}

fn is_public_ipv6(ip: Ipv6Addr) -> bool {
    if let Some(v4) = ip.to_ipv4_mapped() {
        return is_public_ipv4(v4);
    }
    let seg = ip.segments();
    !(ip.is_loopback()
        || ip.is_unspecified()
        || ip.is_multicast()
        // fc00::/7 unique-local
        || (seg[0] & 0xfe00) == 0xfc00
        // fe80::/10 link-local
        || (seg[0] & 0xffc0) == 0xfe80
        // 2001:db8::/32 documentation
        || (seg[0] == 0x2001 && seg[1] == 0x0db8)
        // 2002::/16 6to4 can encapsulate private IPv4
        || seg[0] == 0x2002
        // 64:ff9b::/96 NAT64 can map private IPv4
        || (seg[0] == 0x0064 && seg[1] == 0xff9b))
}

fn is_local_hostname(host: &str) -> bool {
    let host = host.trim_end_matches('.').to_ascii_lowercase();
    host == "localhost"
        || host.ends_with(".localhost")
        || host.ends_with(".local")
        || host.ends_with(".internal")
        || host.ends_with(".home.arpa")
}

fn validate_fetch_url(url: &reqwest::Url) -> Result<(), String> {
    match url.scheme() {
        "http" | "https" => {}
        _ => return Err("only http/https URLs are allowed".into()),
    }
    if !url.username().is_empty() || url.password().is_some() {
        return Err("URLs with embedded credentials are not allowed".into());
    }
    let host = url
        .host_str()
        .ok_or_else(|| "URL has no host".to_string())?;
    if is_local_hostname(host) {
        return Err("refusing to fetch a local hostname".into());
    }
    let port = url.port_or_known_default().unwrap_or(80);
    let addrs: Vec<SocketAddr> = (host, port)
        .to_socket_addrs()
        .map_err(|e| format!("cannot resolve host: {e}"))?
        .collect();
    if addrs.is_empty() {
        return Err("cannot resolve host".into());
    }
    if addrs.iter().any(|a| !is_public_ip(a.ip())) {
        return Err("refusing to fetch a private/loopback address".into());
    }
    Ok(())
}

fn fetch_image_bytes_impl(url_str: &str) -> Result<FetchedImage, String> {
    let url = reqwest::Url::parse(url_str).map_err(|e| format!("invalid URL: {e}"))?;
    validate_fetch_url(&url)?;
    let client = reqwest::blocking::Client::builder()
        .timeout(Duration::from_secs(20))
        .connect_timeout(Duration::from_secs(10))
        .redirect(reqwest::redirect::Policy::custom(|attempt| {
            if attempt.previous().len() >= 5 {
                return attempt.error(std::io::Error::other("too many redirects"));
            }
            match validate_fetch_url(attempt.url()) {
                Ok(()) => attempt.follow(),
                Err(e) => attempt.error(std::io::Error::other(e)),
            }
        }))
        .user_agent(concat!("rustmd/", env!("CARGO_PKG_VERSION")))
        .build()
        .map_err(|e| e.to_string())?;
    let response = client
        .get(url.clone())
        .header(reqwest::header::ACCEPT, "image/*,*/*;q=0.8")
        .send()
        .map_err(|e| e.to_string())?;
    let status = response.status();
    if !status.is_success() {
        return Err(format!("HTTP {}", status.as_str()));
    }
    validate_fetch_url(response.url())?;
    if response
        .content_length()
        .is_some_and(|len| len > IMAGE_LIMIT)
    {
        return Err("image too large (> 25 MB)".into());
    }
    let mime = response
        .headers()
        .get(reqwest::header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .map(|v| v.split(';').next().unwrap_or(v).trim().to_ascii_lowercase())
        .filter(|v| !v.is_empty())
        .unwrap_or_else(|| "application/octet-stream".to_string());
    let mut bytes = Vec::new();
    response
        .take(IMAGE_LIMIT + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| e.to_string())?;
    if bytes.len() as u64 > IMAGE_LIMIT {
        return Err("image too large (> 25 MB)".into());
    }
    Ok(FetchedImage { bytes, mime })
}

/// Fetch a remote image (http/https only). Used by PNG/PDF export:
/// html2canvas cannot draw cross-origin images into its canvas (CORS
/// taint), which is why external pictures came out blank. The backend
/// fetch refuses loopback/private targets and validates every redirect.
#[tauri::command]
fn fetch_image_bytes(window: tauri::WebviewWindow, url: String) -> Result<FetchedImage, String> {
    require_main(&window)?;
    fetch_image_bytes_impl(&url)
}

// ---------------- Vault image serving (`rmd` protocol) ----------------
//
// The webview page origin (tauri://localhost in release, the Vite dev
// server in dev) cannot read the filesystem: a relative <img> src like
// `chart.png` resolves against the APP URL and 404s, and file:///… is
// blocked for an http origin. Notes reference vault files by path, so the
// frontend rewrites local image sources to the `rmd` custom URI scheme,
// which this serves strictly from the CURRENTLY OPEN notes root.
//
// URL contract (the platform origin uses the same workaround form Tauri/
// wry use for the asset protocol on Windows — WebView2 cannot serve a
// bare custom scheme, so it is intercepted as `http://rmd.localhost/*`):
//   Windows: http://rmd.localhost/<percent-encoded absolute path>
//   others:  rmd://localhost/<percent-encoded absolute path>
// The handler always receives the reverted `rmd://localhost/…` URI.
//
// The notes root is dynamic (the user opens arbitrary folders), so unlike
// the static-scope asset protocol it is set at runtime via
// `set_notes_root`, and every request is containment-checked against it —
// the same escape-guard posture as `resolve_in_root` for note paths.
// Images OUTSIDE the open vault are refused by design.

const MAX_IMAGE_BYTES: u64 = 25 * 1024 * 1024; // 25 MB
const CACHE_MAX_ENTRIES: usize = 64;
const CACHE_MAX_BYTES: usize = 64 * 1024 * 1024; // 64 MB
const NOT_FOUND: &str = "file not found";
const TOO_LARGE: &str = "image too large (> 25 MB)";

/// Resolve an absolute path requested from the webview and verify it
/// stays inside the notes root. Canonicalization (rather than component
/// walking) resolves `..`, junctions and case, so an escaped path cannot
/// sneak through — the same posture as `resolve_in_root`.
fn resolve_vault_file(root: &Path, path_str: &str) -> Result<PathBuf, String> {
    let p = Path::new(path_str);
    if !p.is_absolute() {
        return Err("absolute path required".into());
    }
    if !p.exists() {
        return Err(NOT_FOUND.into());
    }
    let file = strip_extended_prefix(&fs::canonicalize(p).map_err(|e| e.to_string())?);
    let canon_root = strip_extended_prefix(&fs::canonicalize(root).map_err(|e| e.to_string())?);
    if !file.starts_with(&canon_root) {
        return Err("path escapes notes root".into());
    }
    Ok(file)
}

/// Content type by file extension. (Magic-byte sniffing would be more
/// thorough, but notes embed images by extension and this keeps the
/// handler dependency-free; unknown extensions still display — browsers
/// sniff image bytes on their own.)
fn mime_for_path(p: &Path) -> &'static str {
    match p
        .extension()
        .and_then(|e| e.to_str())
        .map(|e| e.to_ascii_lowercase())
        .as_deref()
    {
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        Some("bmp") => "image/bmp",
        Some("avif") => "image/avif",
        Some("svg") => "image/svg+xml",
        Some("ico") => "image/x-icon",
        Some("html" | "htm") => "text/html; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("json") => "application/json; charset=utf-8",
        Some("woff") => "font/woff",
        Some("woff2") => "font/woff2",
        Some("ttf") => "font/ttf",
        Some("otf") => "font/otf",
        Some("txt" | "md") => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

struct CacheEntry {
    mtime: SystemTime,
    bytes: Vec<u8>,
}

struct CacheInner {
    entries: HashMap<PathBuf, CacheEntry>,
    total_bytes: usize,
}

/// mtime-validated, byte-budgeted cache for vault files. The preview
/// re-renders (debounced) on every keystroke and each render re-requests
/// every `<img>` through the protocol — without this, every render would
/// re-read multi-MB images from disk. The budget prevents the old
/// 64 × 25 MB worst case from pinning gigabytes of memory.
struct VaultFileCache {
    inner: Mutex<CacheInner>,
}

impl VaultFileCache {
    fn new() -> Self {
        Self {
            inner: Mutex::new(CacheInner {
                entries: HashMap::new(),
                total_bytes: 0,
            }),
        }
    }

    fn clear(&self) {
        let mut inner = self.inner.lock().unwrap();
        inner.entries.clear();
        inner.total_bytes = 0;
    }

    /// Returns the file bytes, serving from the cache while the file's
    /// mtime is unchanged.
    fn read(&self, canonical: &Path) -> Result<Vec<u8>, String> {
        let meta = fs::metadata(canonical).map_err(|e| e.to_string())?;
        if !meta.is_file() {
            return Err(NOT_FOUND.into());
        }
        if meta.len() > MAX_IMAGE_BYTES {
            return Err(TOO_LARGE.into());
        }
        let mtime = meta.modified().map_err(|e| e.to_string())?;
        {
            let inner = self.inner.lock().unwrap();
            if let Some(entry) = inner.entries.get(canonical)
                && entry.mtime == mtime
            {
                return Ok(entry.bytes.clone());
            }
        }
        let bytes = fs::read(canonical).map_err(|e| e.to_string())?;
        let mut inner = self.inner.lock().unwrap();
        if inner.entries.len() >= CACHE_MAX_ENTRIES {
            inner.entries.clear();
            inner.total_bytes = 0;
        }
        while inner.total_bytes.saturating_add(bytes.len()) > CACHE_MAX_BYTES
            && !inner.entries.is_empty()
        {
            let Some(key) = inner.entries.keys().next().cloned() else {
                break;
            };
            if let Some(old) = inner.entries.remove(&key) {
                inner.total_bytes = inner.total_bytes.saturating_sub(old.bytes.len());
            }
        }
        if let Some(old) = inner.entries.remove(canonical) {
            inner.total_bytes = inner.total_bytes.saturating_sub(old.bytes.len());
        }
        if bytes.len() <= CACHE_MAX_BYTES {
            inner.total_bytes = inner.total_bytes.saturating_add(bytes.len());
            inner.entries.insert(
                canonical.to_path_buf(),
                CacheEntry {
                    mtime,
                    bytes: bytes.clone(),
                },
            );
        }
        Ok(bytes)
    }
}

/// App state for the `rmd` protocol: the open notes root (set by the
/// frontend via `set_notes_root`) plus the byte cache.
struct VaultState {
    root: Mutex<Option<PathBuf>>,
    cache: Arc<VaultFileCache>,
}

impl VaultState {
    fn new() -> Self {
        Self {
            root: Mutex::new(None),
            cache: Arc::new(VaultFileCache::new()),
        }
    }
}

/// Remember the notes root the frontend just opened, so the `rmd` image
/// protocol (and `read_local_image`) know which vault to serve.
#[tauri::command]
fn set_notes_root(
    window: tauri::WebviewWindow,
    state: tauri::State<'_, VaultState>,
    dir: String,
) -> Result<(), String> {
    require_main(&window)?;
    let root = Path::new(&dir);
    if !root.is_dir() {
        return Err(format!("directory not found: {dir}"));
    }
    let canon = strip_extended_prefix(&fs::canonicalize(root).map_err(|e| e.to_string())?);
    state.cache.clear();
    *state.root.lock().unwrap() = Some(canon);
    Ok(())
}

/// Read an image file from the open vault (same containment check as the
/// `rmd` protocol). Used by PNG/PDF/HTML export: html2canvas cannot draw
/// images from the rmd origin into its canvas (foreign origin), so the
/// export inlines them as data: URLs built from these bytes — the same
/// proven path used for remote images.
#[tauri::command]
fn read_local_image(
    window: tauri::WebviewWindow,
    state: tauri::State<'_, VaultState>,
    path: String,
) -> Result<LocalImage, String> {
    require_main(&window)?;
    let root = state
        .root
        .lock()
        .unwrap()
        .clone()
        .ok_or_else(|| "notes root not set".to_string())?;
    let file = resolve_vault_file(&root, &path)?;
    let mime = mime_for_path(&file).to_string();
    let bytes = state.cache.read(&file)?;
    Ok(LocalImage { bytes, mime })
}

/// The `rmd` protocol handler body (kept out of the closure so it can be
/// unit-tested and the closure stays trivially Send).
fn serve_rmd(
    root: Option<PathBuf>,
    cache: &VaultFileCache,
    request: &tauri::http::Request<Vec<u8>>,
) -> tauri::http::Response<Vec<u8>> {
    use tauri::http::{Response, StatusCode};
    let text = |status: StatusCode, body: &str| -> Response<Vec<u8>> {
        Response::builder()
            .status(status)
            .header("Content-Type", "text/plain; charset=utf-8")
            .header("Cache-Control", "no-store")
            .body(body.as_bytes().to_vec())
            .expect("static response")
    };
    if request.method() != tauri::http::Method::GET {
        return text(StatusCode::METHOD_NOT_ALLOWED, "method not allowed");
    }
    // Sandboxed HTML previews are null-origin; the hidden HTML export window
    // uses the rmdhtml origin. Do not let their scripts CORS-read the whole
    // vault through the image protocol (plain <img>/<script>/<link> requests
    // do not carry Origin and still work for local assets).
    let origin = request
        .headers()
        .get("origin")
        .and_then(|value| value.to_str().ok());
    // Only the app webview may CORS-read vault files. No-Origin requests are
    // ordinary subresources (`<img>`, `<link>`, classic `<script>`), which
    // cannot read a response. Everything else — sandboxed previews, the
    // hidden export window, remote iframes — is rejected.
    let dest = request
        .headers()
        .get("sec-fetch-dest")
        .and_then(|value| value.to_str().ok());
    let preview_origin = origin.is_some_and(|o| {
        o == "null"
            || o.starts_with("http://rmdhtml.localhost")
            || o.starts_with("rmdhtml://localhost")
    });
    // WebKit sends `Origin: null` for classic scripts/stylesheets in the
    // null-origin preview (WebView2 usually does not). Allow those subresource
    // destinations, plus fonts, while keeping fetch/XHR (empty destination)
    // and documents blocked so vault text stays unreadable.
    let preview_subresource = preview_origin && matches!(dest, Some("font" | "script" | "style"));
    let allowed_origin = if preview_subresource {
        origin
    } else {
        match origin {
            None => None,
            Some("tauri://localhost")
            | Some("http://tauri.localhost")
            | Some("https://tauri.localhost")
            | Some("http://127.0.0.1:5173") => Some(origin.unwrap()),
            Some(o) if o.starts_with("http://127.0.0.1:") || o.starts_with("http://localhost:") => {
                Some(o)
            }
            Some(_) => return text(StatusCode::FORBIDDEN, "forbidden origin"),
        }
    };
    // `rmd://localhost/<percent-encoded absolute path>`
    let raw = request
        .uri()
        .path()
        .strip_prefix('/')
        .unwrap_or_else(|| request.uri().path());
    let path = percent_encoding::percent_decode_str(raw)
        .decode_utf8_lossy()
        .to_string();
    if path.trim().is_empty() {
        return text(StatusCode::BAD_REQUEST, "empty path");
    }
    let Some(root) = root else {
        return text(StatusCode::FORBIDDEN, "notes root not set");
    };
    match resolve_vault_file(&root, &path) {
        Err(e) if e == NOT_FOUND => text(StatusCode::NOT_FOUND, &e),
        Err(e) => text(StatusCode::FORBIDDEN, &e),
        Ok(file) => match cache.read(&file) {
            Err(e) if e == NOT_FOUND => text(StatusCode::NOT_FOUND, &e),
            Err(e) if e == TOO_LARGE => text(StatusCode::PAYLOAD_TOO_LARGE, &e),
            Err(e) => text(StatusCode::INTERNAL_SERVER_ERROR, &e),
            Ok(bytes) => {
                let mime = mime_for_path(&file);
                let mut builder = Response::builder()
                    .header("Content-Type", mime)
                    .header("Cache-Control", "no-store")
                    .header("X-Content-Type-Options", "nosniff");
                // A vault HTML/SVG loaded as a document must not run active
                // content with rmd-origin access to the rest of the vault.
                if mime.starts_with("text/html") || mime == "image/svg+xml" {
                    builder = builder.header(
                        "Content-Security-Policy",
                        "sandbox; default-src 'none'; style-src 'unsafe-inline'; img-src 'self' data:; font-src 'self' data:",
                    );
                }
                if let Some(origin) = allowed_origin {
                    builder = builder
                        .header("Access-Control-Allow-Origin", origin)
                        .header("Vary", "Origin");
                }
                builder.body(bytes).expect("image response")
            }
        },
    }
}

